export const LANGUAGE_DISPLAY_NAMES = {
  'zh-TW': '繁體中文',
  en: 'English',
  ja: '日本語'
};

export const MONTH_SHORT_EN = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

export const WEEKDAY_LABELS_BY_LOCALE = {
  'zh-TW': ['週日', '週一', '週二', '週三', '週四', '週五', '週六'],
  en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'],
  ja: ['日', '月', '火', '水', '木', '金', '土']
};

export function detectDeviceLocale() {
  try {
    const langs = Array.isArray(navigator?.languages) && navigator.languages.length > 0
      ? navigator.languages
      : [navigator?.language || ''];
    for (const raw of langs) {
      const tag = String(raw || '').trim().toLowerCase();
      if (!tag) continue;
      if (tag.startsWith('ja')) return 'ja';
      if (tag.startsWith('zh')) return 'zh-TW';
      if (tag.startsWith('en')) return 'en';
    }
  } catch {
    // 非瀏覽器測試環境
  }
  return 'zh-TW';
}

export function getLanguageSetting() {
  try {
    const stored = (localStorage.getItem(LANGUAGE_STORAGE_KEY) || '').trim();
    if (!stored || stored === 'auto') return 'auto';
    if (SUPPORTED_LOCALES.includes(stored)) return stored;
  } catch {
    // 忽略儲存空間受限
  }
  return 'auto';
}

export function setLanguageSetting(pref) {
  const next = pref === 'auto' || !SUPPORTED_LOCALES.includes(pref) ? 'auto' : pref;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
  } catch {
    // 忽略儲存空間受限
  }
  return next;
}

export function getActiveLocale() {
  const pref = getLanguageSetting();
  return pref === 'auto' ? detectDeviceLocale() : pref;
}

export function getHtmlLangTag(locale = getActiveLocale()) {
  if (locale === 'en') return 'en';
  if (locale === 'ja') return 'ja';
  return 'zh-Hant';
}

export function t(key, params = {}, locale = getActiveLocale()) {
  const table = DICTIONARY[locale] || DICTIONARY['zh-TW'];
  const template = table[key] ?? DICTIONARY['zh-TW'][key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) =>
    params[name] !== undefined && params[name] !== null ? String(params[name]) : ''
  );
}

// 格式化歷史紀錄日期與星期（配合各語系習慣）
export function formatLocalizedHistoryDate(ymd, currentYear, weekdayIndex, locale = getActiveLocale()) {
  const str = String(ymd || '').slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(str)) return str;
  const [y, m, d] = str.split('-').map(Number);
  const mm = String(m).padStart(2, '0');
  const dd = String(d).padStart(2, '0');
  const weekdays = WEEKDAY_LABELS_BY_LOCALE[locale] || WEEKDAY_LABELS_BY_LOCALE['zh-TW'];
  const wd = weekdayIndex !== null && weekdayIndex !== undefined ? (weekdays[weekdayIndex] || '') : '';
  const yy = String(y).slice(-2);

  if (locale === 'ja') {
    const datePart = y !== currentYear ? `${yy}/${mm}/${dd}` : `${mm}/${dd}`;
    return wd ? `${datePart}(${wd})` : datePart;
  }
  const datePart = y !== currentYear ? `${yy}/${mm}/${dd}` : `${mm}/${dd}`;
  return wd ? `${datePart} ${wd}` : datePart;
}

// 將目前語系套用至靜態 HTML 節點（透過 data-i18n* 屬性）
export function applyI18nToDOM(root = typeof document !== 'undefined' ? document : null) {
  if (!root) return;
  const locale = getActiveLocale();
  if (typeof document !== 'undefined' && root === document) {
    document.documentElement.lang = getHtmlLangTag(locale);
    document.title = t('app.title', {}, locale);
  }

  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key, {}, locale);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.setAttribute('placeholder', t(key, {}, locale));
  });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria-label');
    if (key) el.setAttribute('aria-label', t(key, {}, locale));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key, {}, locale));
  });
}
